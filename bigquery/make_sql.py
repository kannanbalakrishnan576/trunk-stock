"""Write one BigQuery AI.FORECAST query per problem code.

The local script (forecast_timesfm.py) runs the TimesFM 3.0 open weights,
which are licensed for non-commercial use. In production the same model is
licensed through BigQuery. These queries are the production path: same
targets (rolling 4-week attach rate per candidate part), same known-future
covariates (temperature, install-base units at risk), same 12-week horizon.

  python bigquery/make_sql.py          writes bigquery/forecast_P01.sql ...
  bash bigquery/load.sh                loads data/*.csv into dataset `trunk`
  bq query --use_legacy_sql=false < bigquery/forecast_P02.sql

Syntax follows Google's AI.FORECAST reference for TimesFM 3.0 (Preview,
October 2026). Not run as part of this repo: it needs a GCP project.
"""
import csv
import os
import re
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(HERE), "data")

cands = defaultdict(list)
with open(os.path.join(DATA, "problem_parts.csv")) as f:
    for r in csv.DictReader(f):
        cands[r["problem_code"]].append(r["part_id"])


def col(part):
    return re.sub(r"[^a-z0-9]+", "_", part.lower()).strip("_")


for problem, parts in sorted(cands.items()):
    cols = [col(p) for p in parts]
    sums = ",\n    ".join(f"SUM(IF(u.part_id = '{p}', u.uses, 0)) AS {c}"
                          for p, c in zip(parts, cols))
    rates = ",\n    ".join(f"SAFE_DIVIDE(SUM({c}) OVER w, SUM(jobs) OVER w) AS {c}"
                           for c in cols)
    picks = ", ".join(f"r.{c}" for c in cols)
    targets = ", ".join(f"'{c}'" for c in cols)
    sql = f"""-- Forecast the parts mix for problem {problem}, every region, next 12 weeks.
-- Target: rolling 4-week attach rate per candidate part (share of jobs using it).
-- Covariates known ahead: forecast temperature, install-base units at risk.
-- Generated by bigquery/make_sql.py.

WITH weekly AS (
  SELECT
    j.week, j.region, j.jobs,
    {sums}
  FROM trunk.jobs_weekly AS j
  LEFT JOIN trunk.part_usage_weekly AS u
    USING (week, region, problem_code)
  WHERE j.problem_code = '{problem}'
  GROUP BY j.week, j.region, j.jobs
),
rolling AS (
  SELECT
    week, region,
    {rates}
  FROM weekly
  WINDOW w AS (PARTITION BY region ORDER BY week ROWS BETWEEN 3 PRECEDING AND CURRENT ROW)
),
-- History rows carry the targets; the 12 future rows carry NULL targets and
-- the covariates, which is how AI.FORECAST knows the horizon's conditions.
data AS (
  SELECT
    wx.week, wx.region,
    {picks},
    wx.avg_temp_f,
    ib.units_at_risk
  FROM trunk.weather_weekly AS wx
  JOIN trunk.install_base_weekly AS ib
    ON ib.week = wx.week AND ib.region = wx.region AND ib.problem_code = '{problem}'
  LEFT JOIN rolling AS r
    ON r.week = wx.week AND r.region = wx.region
)
SELECT *
FROM AI.FORECAST(
  TABLE data,
  model => 'TimesFM 3.0',
  timestamp_col => 'week',
  id_cols => ['region'],
  target_cols => [{targets}],
  future_covariate_cols => ['avg_temp_f', 'units_at_risk'],
  horizon => 12,
  confidence_level => 0.8       -- 80% interval: the 10th and 90th percentiles
);
"""
    path = os.path.join(HERE, f"forecast_{problem}.sql")
    with open(path, "w") as f:
        f.write(sql)
    print("wrote", os.path.relpath(path))
